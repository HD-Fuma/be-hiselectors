    `c`.`campaign_id`,
    `c`.`title`,
    COUNT(`cp`.`campaign_product_id`) AS `product_count`,
    SUM(`p`.`status` = 'ON_SALE') AS `on_sale_count`,
    SUM(`p`.`status` = 'SOLD_OUT') AS `sold_out_count`,
    SUM(`p`.`status` = 'SALE_STOPPED') AS `sale_stopped_count`
FROM `campaign` AS `c`
LEFT JOIN `campaign_product` AS `cp`
    ON `cp`.`campaign_id` = `c`.`campaign_id`
LEFT JOIN `product` AS `p`
    ON `p`.`product_id` = `cp`.`product_id`
GROUP BY `c`.`campaign_id`, `c`.`title`
ORDER BY `c`.`campaign_id`;

SELECT COUNT(*) AS `invalid_campaign_product_count`
FROM (
    SELECT
        `campaign_id`,
        COUNT(*) AS `product_count`
    FROM `campaign_product`
    GROUP BY `campaign_id`
    HAVING COUNT(*) NOT BETWEEN 30 AND 40
) AS `invalid_campaigns`;

-- 검증 2: 같은 캠페인 안에서 동일 상품이 중복 연결되면 안 된다.
SELECT COUNT(*) AS `duplicate_campaign_product_pair_count`
FROM (
    SELECT
        `campaign_id`,
        `product_id`
    FROM `campaign_product`
    GROUP BY `campaign_id`, `product_id`
    HAVING COUNT(*) > 1
) AS `duplicate_pairs`;

-- 검증 3: 진행 중 캠페인에는 판매 중인 상품만 있어야 한다.
SELECT COUNT(*) AS `active_campaign_unavailable_product_count`
FROM `campaign_product` AS `cp`
INNER JOIN `campaign` AS `c`
    ON `c`.`campaign_id` = `cp`.`campaign_id`
INNER JOIN `product` AS `p`
    ON `p`.`product_id` = `cp`.`product_id`
WHERE DATE('2026-08-31') BETWEEN `c`.`start_date` AND `c`.`end_date`
  AND `p`.`status` <> 'ON_SALE';

-- 검증 4: 전체 연결 수는 729건이어야 한다.
SELECT
    COUNT(*) AS `campaign_product_count`,
    MIN(`campaign_product_id`) AS `min_campaign_product_id`,
    MAX(`campaign_product_id`) AS `max_campaign_product_id`
FROM `campaign_product`;

