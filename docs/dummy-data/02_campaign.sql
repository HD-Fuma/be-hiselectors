-- =========================================================
-- 기준일 상태 분포 검증
-- ACTIVE 5건, ENDED 15건이어야 한다.
-- =========================================================

SELECT
    CASE
        WHEN DATE('2026-08-31') < `start_date` THEN 'SCHEDULED'
    WHEN DATE('2026-08-31') > `end_date` THEN 'ENDED'
    ELSE 'ACTIVE'
END AS `campaign_status`,
    COUNT(*) AS `campaign_count`
FROM `campaign`
WHERE `is_deleted` = 0
GROUP BY `campaign_status`
ORDER BY FIELD(
    `campaign_status`,
    'ACTIVE',
    'ENDED',
    'SCHEDULED'
);


-- =========================================================
-- 캠페인 목록 검증
-- ID가 증가할수록 대체로 최근 캠페인이 된다.
-- =========================================================

SELECT
    `campaign_id`,
    `title`,
    `start_date`,
    `end_date`,
    CASE
        WHEN DATE('2026-08-31') < `start_date` THEN 'SCHEDULED'
    WHEN DATE('2026-08-31') > `end_date` THEN 'ENDED'
    ELSE 'ACTIVE'
END AS `campaign_status`
FROM `campaign`
ORDER BY `campaign_id`;